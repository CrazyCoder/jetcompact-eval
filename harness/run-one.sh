#!/usr/bin/env bash
# One headless Claude Code run of one task in one arm, as several user turns.
#   run-one.sh <arm: builtin|jetcompact> <task-dir> <run-id> [variant]
# <task-dir> holds repo/ (copied fresh to runs/<run-id>/work) and steps/NN.md,
# one user turn each, sent in order to one session (--resume). Compaction
# happens between turns, as in an interactive session.
# [variant] names harness/variants/<variant>.json (default: default), the
# jetcompact plugin options for this run; keys starting with "_" (such as
# "_provider_env") are not passed to the plugin. The builtin arm ignores it.
# Output in runs/<run-id>/: stream-NN.jsonl, debug-NN.log, stderr-NN.log,
# skipped-NN (a /compact step below the trigger), settings.json (jetcompact
# arm), meta.json.
#
# Environment: WINDOW (context window the percentages use, 150000),
# TRIGGER_PCT (a /compact step runs only at or above this percentage of
# WINDOW, as automatic compaction would; 0 runs every one; 60), PLUGIN_DIR
# (the jetcompact checkout to load; pin it to a worktree of the commit under
# test), MODEL (sonnet), COMPACT_AS (auto).
#
# Do not edit this file while runs execute: bash reads it as it goes.
set -euo pipefail
arm=$1 task=$2 id=$3 variant=${4:-default}
root=$(cd "$(dirname "$0")/.." && pwd)
task=$(cd "$task" && pwd)
variant_file="$root/harness/variants/$variant.json"
[ -f "$variant_file" ] || { echo "no variant file $variant_file" >&2; exit 2; }
out="$root/runs/$id"
wout=$(cygpath -m "$out")
rm -rf "$out" && mkdir -p "$out"
cp -r "$task/repo" "$out/work"
(cd "$out/work" && git init -q && git add -A && git -c user.email=eval@local -c user.name=eval commit -qm base)

session=$(pwsh -NoProfile -Command '[guid]::NewGuid().ToString()' | tr -d '\r\n')
window=${WINDOW:-150000}
trigger_pct=${TRIGGER_PCT:-60}
plugin_dir=${PLUGIN_DIR:-C:/projects/jetcompact}

export CLAUDE_CODE_ENABLE_FUNCTION_HOOKS=1
export CLAUDE_CODE_AUTO_COMPACT_WINDOW=$window
export TYPESAFE_API_KEY=$(jq -r '.env.TYPESAFE_API_KEY // empty' "$HOME/.claude/settings.json")
export MSYS_NO_PATHCONV=1

plugin=()
if [ "$arm" = jetcompact ]; then
  # Windows jq reads Windows paths only.
  jq '{pluginConfigs: {jetcompact: {options: with_entries(select(.key | startswith("_") | not))}}}' "$(cygpath -m "$variant_file")" > "$out/settings.json"
  plugin=(--plugin-dir "$plugin_dir" --settings "$wout/settings.json")
fi

start=$(date +%s)
failed=0
n=0
last_ctx=0
compacted=0
skipped=0
for step in "$task"/steps/*.md; do
  n=$((n + 1))
  tag=$(printf '%02d' "$n")
  session_arg=(--session-id "$session")
  [ "$n" -gt 1 ] && session_arg=(--resume "$session")
  prompt=$(cat "$step")
  if [ "$prompt" = /compact ]; then
    # Automatic compaction fires only once the context reaches the trigger.
    if [ $((last_ctx * 100)) -lt $((window * trigger_pct)) ]; then
      echo "$last_ctx" > "$out/skipped-$tag"
      skipped=$((skipped + 1))
      continue
    fi
    compacted=$((compacted + 1))
    # JetCompact treats a typed /compact as an explicit request (applied
    # whenever it frees anything); the args it gives the /compact it queues
    # itself mark it automatic, so its size guards and built-in fallback
    # apply. COMPACT_AS=typed sends it bare.
    if [ "$arm" = jetcompact ] && [ "${COMPACT_AS:-auto}" = auto ]; then
      prompt='/compact automatic, from jetcompact'
    fi
  fi
  set +e
  (cd "$out/work" && claude -p "$prompt" \
    --model "${MODEL:-sonnet}" \
    --setting-sources project \
    --strict-mcp-config \
    --dangerously-skip-permissions \
    "${session_arg[@]}" \
    --output-format stream-json --verbose \
    --debug-file "$wout/debug-$tag.log" \
    "${plugin[@]}" \
    < /dev/null > "$out/stream-$tag.jsonl" 2> "$out/stderr-$tag.log")
  status=$?
  set -e
  [ "$status" -ne 0 ] && { failed=$status; break; }
  # Context of the step's last model request, for the next /compact's trigger.
  ctx=$(jq -s '[.[] | select(.type == "assistant") | .message.usage | select(.) | ((.input_tokens // 0) + (.cache_read_input_tokens // 0) + (.cache_creation_input_tokens // 0))] | last // 0' "$(cygpath -m "$out/stream-$tag.jsonl")")
  [ "$ctx" -gt 0 ] && last_ctx=$ctx
done
end=$(date +%s)

jq -n --arg arm "$arm" --arg task "$(basename "$task")" --arg id "$id" --arg variant "$variant" --arg session "$session" \
  --argjson exit "$failed" --argjson steps "$n" --argjson seconds $((end - start)) --argjson window "$window" \
  --argjson triggerPct "$trigger_pct" --argjson compacted "$compacted" --argjson skipped "$skipped" \
  --arg model "${MODEL:-sonnet}" --arg compactAs "${COMPACT_AS:-auto}" --arg plugin "$plugin_dir" \
  '{arm:$arm, task:$task, id:$id, variant:$variant, session:$session, exit:$exit, steps:$steps, seconds:$seconds, window:$window, triggerPct:$triggerPct, compacted:$compacted, skipped:$skipped, model:$model, compactAs:$compactAs, plugin:$plugin}' > "$out/meta.json"
cat "$out/meta.json"
